import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { once } from 'node:events';
import { get } from 'node:http';
import { createApp } from '../server/app.mjs';
import { createConfigStore } from '../server/config.mjs';
test('API local valida token/origem, deduplica jobs e salva a transcrição', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'antes-do-play-test-'));
  assert.equal(dirname(resolve(dataDir)), resolve(tmpdir()));
  let calls = 0; let complete;
  const waiting = new Promise(resolve => { complete = resolve; });
  const app = createApp({ token: 'local-test-token', config: { apiKey: 'private-api-key', model: 'test-model' }, dataDir, summarize: async () => { calls++; await waiting; return 'Um resumo de teste completo.'; } });
  app.listen(0, '127.0.0.1'); await once(app, 'listening');
  const base = `http://127.0.0.1:${app.address().port}`;
  t.after(async () => { complete(); app.closeAllConnections(); await new Promise(resolve => app.close(resolve)); await rm(dataDir, { recursive: true, force: true }); });
  const health = await (await fetch(base + '/health')).json();
  assert.equal(health.configured, true); assert.ok(!JSON.stringify(health).includes('private-api-key'));
  assert.equal((await fetch(base + '/api/status')).status, 401);
  const operaOrigin = `opera-extension://${'b'.repeat(32)}`;
  const operaHeaders = { Authorization: 'Bearer local-test-token', Origin: operaOrigin };
  const operaStatus = await fetch(base + '/api/status', { headers: operaHeaders });
  assert.equal(operaStatus.status, 200);
  assert.equal(operaStatus.headers.get('access-control-allow-origin'), operaOrigin);
  const preflight = await fetch(base + '/api/jobs', { method: 'OPTIONS', headers: { Origin: operaOrigin, 'Access-Control-Request-Method': 'POST', 'Access-Control-Request-Headers': 'authorization,content-type' } });
  assert.equal(preflight.status, 204);
  assert.equal(preflight.headers.get('access-control-allow-origin'), operaOrigin);
  assert.equal((await fetch(base + '/api/status', { headers: { Origin: operaOrigin } })).status, 401);
  assert.equal((await fetch(base + '/api/status', { headers: { Authorization: 'Bearer local-test-token', Origin: 'https://evil.test' } })).status, 403);
  const badHostStatus = await new Promise((resolve, reject) => get(base + '/health', { headers: { Host: 'evil.test' } }, response => { response.resume(); resolve(response.statusCode); }).on('error', reject));
  assert.equal(badHostStatus, 403);
  const headers = { Authorization: 'Bearer local-test-token', 'Content-Type': 'application/json', Origin: `chrome-extension://${'a'.repeat(32)}` };
  const invalid = await fetch(base + '/api/jobs', { method: 'POST', headers, body: '{bad' }); assert.equal(invalid.status, 400);
  assert.equal((await fetch(base + '/api/jobs', { method: 'POST', headers, body: 'null' })).status, 400);
  const input = { url: 'https://www.youtube.com/watch?v=abcdefghijk', title: 'Exemplo', transcript: 'Transcrição para um teste do serviço local. '.repeat(3) };
  const first = await (await fetch(base + '/api/jobs', { method: 'POST', headers, body: JSON.stringify(input) })).json();
  const duplicate = await (await fetch(base + '/api/jobs', { method: 'POST', headers, body: JSON.stringify(input) })).json();
  assert.equal(first.id, duplicate.id);
  complete();
  let result;
  for (let attempt = 0; attempt < 30; attempt++) {
    result = await (await fetch(base + '/api/jobs/' + first.id, { headers })).json();
    if (result.state === 'ready') break;
    await new Promise(resolve => setTimeout(resolve, 10));
  }
  assert.equal(calls, 1); assert.equal(result.state, 'ready'); assert.equal(result.words, 5);
  assert.equal(await readFile(join(dataDir, 'transcripts', 'abcdefghijk.txt'), 'utf8'), input.transcript);
});

test('API configura OpenRouter sem expor chaves e preserva o provedor de um job já iniciado', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'antes-do-play-server-config-'));
  assert.equal(dirname(resolve(dataDir)), resolve(tmpdir()));
  const configStore = await createConfigStore({ dataDir, env: { OPENAI_API_KEY: 'first-secret', OPENAI_MODEL: 'first-model' } });
  let release; const gate = new Promise(resolve => { release = resolve; });
  const snapshots = [];
  let checks = 0;
  const app = createApp({ token: 'local-test-token', configStore, dataDir, summarize: async (_, snapshot) => { snapshots.push(snapshot); await gate; return 'Resumo completo do vídeo.'; }, diagnose: async draft => { checks++; assert.equal(draft.provider, 'openrouter'); assert.equal(draft.apiKey, 'draft-key'); return { ok: true, modelListed: true, message: 'Chave aceita.' }; } });
  app.listen(0, '127.0.0.1'); await once(app, 'listening');
  const base = `http://127.0.0.1:${app.address().port}`;
  t.after(async () => { release(); app.closeAllConnections(); await new Promise(resolve => app.close(resolve)); await rm(dataDir, { recursive: true, force: true }); });
  const headers = { Authorization: 'Bearer local-test-token', 'Content-Type': 'application/json' };
  assert.equal((await fetch(base + '/api/config')).status, 401);
  assert.equal((await fetch(base + '/api/diagnose', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 401);
  const checked = await (await fetch(base + '/api/diagnose', { method: 'POST', headers, body: JSON.stringify({ provider: 'openrouter', apiKey: 'draft-key', model: 'vendor/model', effort: '' }) })).json();
  assert.equal(checked.ok, true); assert.equal(checks, 1); assert.equal(configStore.current().provider, 'openai');
  assert.ok(!JSON.stringify(checked).includes('draft-key'));
  const input = { url: 'https://www.youtube.com/watch?v=abcdefghijk', title: 'Teste', transcript: 'Texto transcrito de teste para resumir.' };
  const first = await (await fetch(base + '/api/jobs', { method: 'POST', headers, body: JSON.stringify(input) })).json();
  const updated = await (await fetch(base + '/api/config', { method: 'POST', headers, body: JSON.stringify({ provider: 'openrouter', apiKey: 'router-secret', model: 'vendor/model', effort: '' }) })).json();
  assert.equal(updated.provider, 'openrouter'); assert.equal(updated.configured, true);
  assert.ok(!JSON.stringify(updated).includes('router-secret'));
  const publicConfig = await (await fetch(base + '/api/config', { headers })).json();
  assert.ok(!JSON.stringify(publicConfig).includes('first-secret')); assert.ok(!JSON.stringify(publicConfig).includes('router-secret'));
  const second = await (await fetch(base + '/api/jobs', { method: 'POST', headers, body: JSON.stringify(input) })).json();
  assert.notEqual(first.id, second.id); assert.equal(second.provider, 'openrouter');
  release();
  let oldJob; let newJob;
  for (let attempt = 0; attempt < 30; attempt++) {
    oldJob = await (await fetch(base + '/api/jobs/' + first.id, { headers })).json();
    newJob = await (await fetch(base + '/api/jobs/' + second.id, { headers })).json();
    if (oldJob.state === 'ready' && newJob.state === 'ready') break;
    await new Promise(resolve => setTimeout(resolve, 10));
  }
  assert.equal(oldJob.model, 'first-model'); assert.equal(newJob.model, 'vendor/model');
  assert.equal(snapshots[0].apiKey, 'first-secret'); assert.equal(snapshots[1].apiKey, 'router-secret');
});
